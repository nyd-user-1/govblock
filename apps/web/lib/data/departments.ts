/**
 * The budget prints an agency inverted — "Health, Department of" — and the
 * list reads it straight. The same words in any order are the same agency;
 * the small words drop out so "State Education Department" meets
 * "Education Department, State".
 */
export function nameKey(name: string) {
  return name
    .toLowerCase()
    .replace(/\(.*?\)/g, " ")
    .replace(/new york state|nys|state of new york/g, " ")
    .replace(/[^a-z0-9 ]+/g, " ")
    .split(/\s+/)
    .filter((w) => w && !["of", "the", "for", "on", "and", "a", "an", "in"].includes(w))
    .sort()
    .join(" ")
}
