export const REGISTRY_KINDS: readonly RegistryKind[] = ["Component", "Card", "Hook", "Library"]

export function registryItem(name: string) {
  return REGISTRY_ITEMS.find((i) => i.name === name) ?? null
}

export const REGISTRY_NAMESPACE = "@44gov"
export const REGISTRY_URL = "https://44gov.nysgpt.com/r/{name}.json"

/** The install command, with the data set when asked for. */
export function installLines(name: string, pm: "pnpm" | "npm" | "yarn" | "bun", withData?: string | null) {
  const items = [`${REGISTRY_NAMESPACE}/${name}`, ...(withData ? [`${REGISTRY_NAMESPACE}/${withData}`] : [])].join(" ")
  const runner = pm === "pnpm" ? "pnpm dlx" : pm === "npm" ? "npx" : pm === "yarn" ? "yarn dlx" : "bunx --bun"
  return [`${runner} shadcn@latest add ${items}`]
}
