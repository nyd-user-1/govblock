// What the @44gov registry publishes: one list, read by /docs/components,
// its per-item pages, the rail, and /docs/blocks. registry.json at the repo
// root is what the build reads — keep the two in step: a name here that is
// not there is a command that 404s, and an item there that is not here has
// no page.
//
// 2026-09-12 (Brendan): the list is meant to grow from eleven to thirty and
// beyond, every entry actually portable and actually publishable, with the
// page each one deserves. The "pro" path ships data with a component: an item
// may name a data set, a second registry item that lands rows beside it.

export type RegistryKind = "Component" | "Card" | "Hook" | "Library"

export type RegistryProp = { name: string; type: string; default?: string; description: string }

export type RegistryItem = {
  name: string
  kind: RegistryKind
  /** One sentence, the way a shadcn component page says it. */
  what: string
  /** Title Case, for the page and the index. */
  title: string
  /** Which primitives it stands on: Base UI (the site's), Radix, either, or none. */
  style: "base" | "radix" | "both" | "none"
  /** The named exports, first one first. */
  exports: string[]
  /** Where it lands in a consumer's tree, without the extension. */
  target: string
  /** The JSX (or call) that uses it. */
  usage: string
  props?: RegistryProp[]
  /** Exported functions worth a signature of their own. */
  functions?: { signature: string; description: string }[]
  /** The usage with rows of your own, where the first usage reads the shipped data set. */
  usageOwn?: string
  /** The rows that ship with it, as a second item, when it has any. */
  data?: { item: string; file: string; what: string; rows: string }
}

